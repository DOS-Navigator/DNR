from __future__ import annotations

import os, sys
from pathlib import Path

def _find_kit() -> Path | None:
    env = os.environ.get("SURFACEKIT_HOME")
    for d in ([Path(env)] if env else []) + [Path(__file__).resolve().parent, *Path(__file__).resolve().parents, Path("C:/dev/scripts")]:
        if (d / "surfacekit.py").is_file():
            return d
    return None

_KIT = _find_kit()
if _KIT is None:
    print("[COULD NOT TELL] surfacekit.py not found beside this driver or via $SURFACEKIT_HOME", file=sys.stderr)
    sys.exit(3)
sys.path.insert(0, str(_KIT))

import argparse
import re
import tempfile
import time
from surfacekit import (TuiSurface, Control, Outcome, emit, negative, ok, unknown,
                        harvest_dropdown, menubar, EXIT_OK, EXIT_USAGE, EXIT_UNKNOWN)

ROOT_DIR = Path(__file__).resolve().parents[2]
BINARY = str(ROOT_DIR / 'build' / 'dn.exe')
ARGS = []
LANDMARK = 'F1 Help  F2 User  F3 View  F4 Edit  F5 Copy  F6 Ren  F7 MkDir  F8 Del  F10 Menu'
STATUS_LINE_AT_START = 'F1 Help  F2 User  F3 View  F4 Edit  F5 Copy  F6 Ren  F7 MkDir  F8 Del  F10 Menu'
EXIT_KEY = 'alt+x'
MENUS = {}
HINTS = {'Help': 'f1',
 'User': 'f2',
 'View': 'f3',
 'Edit': 'f4',
 'Copy': 'f5',
 'Ren': 'f6',
 'MkDir': 'f7',
 'Del': 'f8',
 'Menu': 'f10'}


class Dn(TuiSurface):
    BINARY = BINARY
    ARGS = ARGS
    LANDMARK = LANDMARK
    MENUS = MENUS
    HINTS = HINTS

    def quit(self) -> Outcome:
        """Leave through the app's own Exit (Alt+X then Enter to confirm), and verify it exits."""
        if not self.tui:
            return ok("not running")
        self.tui.key("alt+x")
        self.tui.settle(0.3, 5)
        self.tui.key("enter")
        for _ in range(30):
            if not self.tui.alive():
                return ok("exited cleanly via alt+x + enter")
            time.sleep(0.1)
        self.tui.close()
        return unknown("alt+x did not end the process; the pty was closed instead",
                       screen=[ln for ln in self.tui.lines() if ln.strip()][:8])

    def steps(self, steps: list) -> Outcome:
        """Run a script in ONE session: key:KEY  type:TEXT  wait:TEXT  expect:TEXT
        absent:TEXT  press:HintLabel  settle  screen. Stops at first failed step."""
        log = []
        for s in steps:
            verb, _, arg = s.partition(":")
            if verb == "key":
                self.tui.key(arg)
                self.tui.settle()
            elif verb == "type":
                self.tui.send(arg)
                self.tui.settle()
            elif verb == "settle":
                self.tui.settle(float(arg or 0.6), 15)
            elif verb == "wait":
                if not self.tui.wait_for(arg, 15):
                    return unknown(f"step {s!r}: {arg!r} never appeared", log=log, screen=self.screen())
            elif verb == "expect":
                o = self.find(arg)
                if not o.ok:
                    o.data.update(log=log, screen=self.screen())
                    return o
            elif verb == "absent":
                o = self.find(arg)
                if o.ok:
                    return Outcome(1, f"step {s!r}: {arg!r} IS on screen", {"log": log, "screen": self.screen()})
                if o.code != 1:
                    return o
            elif verb == "press":
                o = self.press(arg)
                if not o.ok:
                    return o
            elif verb == "screen":
                log.append({"screen": self.screen()})
                continue
            else:
                return Outcome(EXIT_USAGE, f"unknown step verb {verb!r}")
            log.append(s)
        return ok(f"{len(steps)} steps completed", log=log, screen=self.screen())

    def screen(self) -> list:
        return [ln for ln in self.tui.lines() if ln.strip()] if self.tui else []


def main(argv=None) -> int:
    # Ensure stdout handles UTF-8 correctly
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    ap = argparse.ArgumentParser(prog="dn_surface.py", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--cwd", default=None, help="working directory (default: current directory)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("selftest", help="start, the landmark must appear, quit through Alt+X + Enter")
    sub.add_parser("screen", help="start, capture screen, and quit")
    p = sub.add_parser("steps", help="run a step script in one session")
    p.add_argument("steps", nargs="+")
    p.add_argument("--args", nargs="*", default=None, help="arguments for the TUI itself")
    a = ap.parse_args(argv)

    cwd = a.cwd or str(ROOT_DIR)
    if a.cmd == "selftest":
        d = Dn(cwd=cwd)
        o = d.start()
        if not o.ok:
            d.close()
            return emit(o, a.json)
        q = d.quit()
        return emit(ok("landmark appeared and DOS Navigator quit cleanly through Alt+X", start=o.data, quit=q.detail)
                    if q.ok else unknown(f"landmark appeared, but: {q.detail}", start=o.data), a.json)
    if a.cmd == "screen":
        d = Dn(cwd=cwd)
        o = d.start()
        if not o.ok:
            d.close()
            return emit(o, a.json)
        scr = d.screen()
        d.quit()
        return emit(ok("screen captured", screen=scr), a.json)
    if a.cmd == "steps":
        d = Dn(args=a.args, cwd=cwd)
        o = d.start()
        if o.ok:
            o = d.steps(a.steps)
            d.quit()
        else:
            d.close()
        return emit(o, a.json)
    return EXIT_USAGE

if __name__ == "__main__":
    sys.exit(main())
